    private void jBotonSolicitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBotonSolicitarActionPerformed

        //Quan apretem el botó de solicitar, recopilem els datos que ha introduit el usuari
        
        
        
        int numeroPersonas = (int) jSpinnerNumeroPersonas.getValue();
        
        boolean presenciaNinos;
        
        //Si esta seleccionat el radio button de si posem a true la variale, sino a false
        if(grupoBotonesPresencia.getSelection().getActionCommand().equals("si")){
            
            presenciaNinos = true;
            
        }else{
            
            presenciaNinos = false;
            
        }
        
        String disponibilidadHoraria = jAreaHorario.getText();
        
        if(numeroPersonas<=0){
            
              JOptionPane.showMessageDialog(null, "Debe haber al menos una persona viviendo en la casa.");
            
        }else{
            
            adoptante.solicitarAdopcion(animal, numeroPersonas, presenciaNinos, disponibilidadHoraria);
            
        }
      
       
        
    }//GEN-LAST:event_jBotonSolicitarActionPerformed

